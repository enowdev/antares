export type MessageKey = keyof typeof en

export type Dict = Partial<Record<MessageKey, string>>

/**
 * Non-English dictionaries are code-split: each is a dynamic import so the
 * initial bundle only ships English. `loadDict` returns the English dict
 * synchronously and defers the rest, memoising resolved and in-flight loads.
 */
const LAZY_DICT_LOADERS: Record<Exclude<Lang, 'en'>, () => Promise<{ default: Dict }>> = {
  id: () => import('./locales/id'),
  ja: () => import('./locales/ja'),
  zh: () => import('./locales/zh'),
  ru: () => import('./locales/ru'),
}

const dictCache: Partial<Record<Lang, Dict>> = { en }
const dictInflight: Partial<Record<Lang, Promise<Dict>>> = {}

function loadDict(lang: Lang): Dict | Promise<Dict> {
  const cached = dictCache[lang]
  if (cached) return cached
  const pending = dictInflight[lang]
  if (pending) return pending
  const loader = LAZY_DICT_LOADERS[lang as Exclude<Lang, 'en'>]
  if (!loader) return en
  const promise = loader()
    .then((mod) => {
      dictCache[lang] = mod.default
      delete dictInflight[lang]
      return mod.default
    })
    .catch((err) => {
      // Drop the failed load entirely — no permanent English cache — so a
      // later switch or retry actually tries the real locale again. Return
      // English for this attempt so the current render keeps working.
      delete dictInflight[lang]
      // eslint-disable-next-line no-console
      console.error(`[i18n] failed to load locale "${lang}"`, err)
      return en
    })
  dictInflight[lang] = promise
  return promise
}

/** Locale tags used for date and number formatting. */
const LOCALE_TAG: Record<Lang, string> = {
  en: 'en-GB',
  id: 'id-ID',
  ja: 'ja-JP',
  zh: 'zh-CN',
  ru: 'ru-RU',
}

export type TFunc = (key: MessageKey, vars?: Record<string, string | number>) => string

interface I18nValue {
  lang: Lang
  setLang: (l: Lang) => void
  t: TFunc
  locale: string
}

const I18nContext = createContext<I18nValue | null>(null)

/** Detects a supported language from the browser, defaulting to English. */
function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'en'
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.toLowerCase().split('-')[0]
    const match = LANGUAGES.find((l) => l.code === base)
    if (match) return match.code
  }
  return 'en'
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [stored, setStored] = useLocalStorage<Lang | 'auto'>('antares.lang', 'auto')
  const lang: Lang = stored === 'auto' ? detectLang() : stored

  // Hold both the resolved dict and the language it belongs to. English is
  // available synchronously; anything else starts as English and swaps in
  // once its chunk arrives. Stale loads (user switching languages faster
  // than the network) are ignored via a per-effect cancellation flag.
  const initial = dictCache[lang] ?? en
  const [dict, setDict] = useState<Dict>(initial)
  const [resolvedLang, setResolvedLang] = useState<Lang>(initial === en ? 'en' : lang)

  useEffect(() => {
    const loaded = loadDict(lang)
    if (!(loaded instanceof Promise)) {
      setDict(loaded)
      setResolvedLang(lang)
      return
    }
    let cancelled = false
    // Fall back to English while the target chunk is fetching, then swap
    // once it resolves — unless the user has already moved on.
    setDict(en)
    setResolvedLang('en')
    loaded.then((resolved) => {
      if (cancelled) return
      setDict(resolved)
      setResolvedLang(resolved === en ? 'en' : lang)
    })
    return () => {
      cancelled = true
    }
  }, [lang])

  // Mirror the *resolved* language onto <html lang> so assistive tech and
  // browser features (hyphenation, spellcheck) match what the user actually
  // sees. Skip while SSR / non-DOM environments have no document.
  useEffect(() => {
    if (typeof document === 'undefined') return
    document.documentElement.lang = resolvedLang
  }, [resolvedLang])

  const t = useCallback<TFunc>(
    (key, vars) => {
      let text: string = dict[key] ?? en[key] ?? key
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, String(value))
        }
      }
      return text
    },
    [dict],
  )

  const value = useMemo<I18nValue>(
    () => ({ lang, setLang: setStored, t, locale: LOCALE_TAG[lang] }),
    [lang, setStored, t],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}

/** Shorthand for components that only need the translate function. */
export function useT(): TFunc {
  return useI18n().t
}

/** Localised relative time, driven by the active language. */
export function useTimeAgo() {
  const { t, locale } = useI18n()
  return useCallback(
    (iso: string | Date | null | undefined): string => {
      if (!iso) return '—'
      const then = typeof iso === 'string' ? new Date(iso) : iso
      const secs = Math.floor((Date.now() - then.getTime()) / 1000)
      if (Number.isNaN(secs)) return '—'
      if (secs < 45) return t('time.justNow')
      if (secs < 3600) return t('time.minutes', { n: Math.floor(secs / 60) })
      if (secs < 86400) return t('time.hours', { n: Math.floor(secs / 3600) })
      if (secs < 604800) return t('time.days', { n: Math.floor(secs / 86400) })
      return then.toLocaleDateString(locale, { day: 'numeric', month: 'short', year: 'numeric' })
    },
    [t, locale],
  )
}
